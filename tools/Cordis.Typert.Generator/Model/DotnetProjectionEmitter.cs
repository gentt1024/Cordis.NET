    private string TypeName(NativeTypeReference type)
    {
        var name = type.Kind switch
        {
            "primitive" => type.Name switch
            {
                "System_Boolean" => "bool",
                "System_Byte" => "byte",
                "System_SByte" => "sbyte",
                "System_Int16" => "short",
                "System_UInt16" => "ushort",
                "System_Int32" => "int",
                "System_UInt32" => "uint",
                "System_Int64" => "long",
                "System_UInt64" => "ulong",
                "System_Single" => "float",
                "System_Double" => "double",
                "System_Decimal" => "decimal",
                "System_Char" => "char",
                "System_String" => "string",
                _ => throw new InvalidDataException("Unsupported CLR primitive " + type.Name)
            },
            "json" => "global::System.Text.Json.JsonElement",
            "named" => Identifier(declarations[type.Name].Name),
            "nullable" => TypeName(type.Arguments.Single()).TrimEnd('?') + "?",
            "array" => TypeName(type.Arguments.Single()) + "[]",
            "collection" => "global::" + type.Name[..type.Name.IndexOf('<')] + "<" +
                string.Join(", ", type.Arguments.Select(TypeName)) + ">",
            _ => throw new InvalidDataException("Unsupported native type kind " + type.Kind)
        };
        return type.Nullability == "Annotated" && type.Kind is not ("nullable" or "json") &&
            (type.Kind is "named" or "array" or "collection" || type.Name == "System_String")
                ? name + "?"
                : name;
    }

    private static bool Nullable(NativeTypeReference type) =>
        type.Kind == "nullable" || type.Nullability == "Annotated";

    private static bool OmitNullDefault(NativeParameter parameter) => parameter.Optional &&
        parameter.Default?.Json == "null" && Nullable(parameter.Type) &&
        parameter.Attributes.Any(attribute =>
            attribute.Name == "System.Diagnostics.CodeAnalysis.DisallowNullAttribute");

    private static string Identifier(string value) => SyntaxFacts.IsValidIdentifier(value) ? value :
        SyntaxFacts.GetKeywordKind(value) != SyntaxKind.None ? "@" + value :
        throw new InvalidDataException("Invalid C# identifier " + value);

    private static string Literal(string value) =>
        Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, true);

    private static string Constant(NativeConstant value) => value.Kind switch
    {
        "carrierDefault" => "default",
        "emptyCollection" => "[]",
        "enum" => "(global::" + value.Type + ")" + value.Json,
        "type" => "typeof(" + JsonSerializer.Deserialize<string>(value.Json) + ")",
        "value" when value.Json == "null" => "null",
        "value" => value.Type.TrimEnd('?') switch
        {
            "string" or "System.String" => Literal(JsonSerializer.Deserialize<string>(value.Json)!),
            "char" or "System.Char" => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(
                JsonSerializer.Deserialize<string>(value.Json)![0],
                true),
            "float" or "System.Single" => value.Json + "F",
            "decimal" or "System.Decimal" => value.Json + "M",
            "ulong" or "System.UInt64" => value.Json + "UL",
            "long" or "System.Int64" => value.Json + "L",
            "uint" or "System.UInt32" => value.Json + "U",
            _ => value.Json
        },
        _ => throw new InvalidDataException("Unsupported projected constant kind " + value.Kind)
    };

    private void EmitAttribute(NativeAttribute attribute, string indent = "")
        => output.AppendLine(indent + AttributeText(attribute));

    private static string ParameterAttributes(NativeAttribute[] attributes) =>
        string.Concat(attributes.Select(attribute => AttributeText(attribute) + " "));

    private static string AttributeText(NativeAttribute attribute)
    {
        var supported = attribute.Name is "System.Text.Json.Serialization.JsonPropertyNameAttribute" or
            "System.Text.Json.Serialization.JsonIgnoreAttribute"
            or "System.Text.Json.Serialization.JsonRequiredAttribute" or
            "System.Text.Json.Serialization.JsonPropertyOrderAttribute"
            or "System.Text.Json.Serialization.JsonNumberHandlingAttribute" or
            "System.Text.Json.Serialization.JsonIncludeAttribute"
            or "System.Text.Json.Serialization.JsonSourceGenerationOptionsAttribute" or
            "System.Text.Json.Serialization.JsonUnmappedMemberHandlingAttribute" or
            "System.Diagnostics.CodeAnalysis.AllowNullAttribute"
            or "System.Diagnostics.CodeAnalysis.DisallowNullAttribute" or
            "System.Diagnostics.CodeAnalysis.MaybeNullAttribute" or "System.Diagnostics.CodeAnalysis.NotNullAttribute";
        if (!supported)
            throw new InvalidDataException(
                "JSON attribute requires an explicitly supported projection: " + attribute.Name);
        return "[global::" + attribute.Name + "(" + string.Join(
            ", ",
            attribute
                .Arguments.Select(Constant)
                .Concat(attribute.NamedArguments.Select(value => value.Name + " = " + Constant(value.Value)))) + ")]";
    }

    private void Docs(string xml, string indent = "", string? filter = null)
    {
        if (string.IsNullOrWhiteSpace(xml))
            return;
        var member = XElement.Parse(xml);
        foreach (var element in member.Elements())
        {
            if (filter == "type" && element.Name.LocalName == "param" ||
                filter == "constructor" && element.Name.LocalName != "param")
                continue;
            foreach (var line in element.ToString().Split('\n'))
                output.AppendLine(indent + "/// " + line.TrimEnd('\r'));
        }
    }
