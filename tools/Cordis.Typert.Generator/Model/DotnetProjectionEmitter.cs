using System.Text;
using System.Text.Json;
using System.Xml.Linq;
using Microsoft.CodeAnalysis.CSharp;

namespace Cordis.Typert.Generator.Model;

internal sealed partial class DotnetProjectionEmitter
{
    private readonly RemoteProjection? model;
    private readonly string client;
    private readonly Dictionary<string, NativeTypeDeclaration> declarations;
    private readonly HashSet<string> reachable = new(StringComparer.Ordinal);
    private readonly StringBuilder output = new();
    private readonly StringBuilder nullabilityHelpers = new();
    private int nullabilityIndex;

    private DotnetProjectionEmitter(RemoteProjection model, string client) : this(model.Types, client)
    {
        this.model = model;
    }

    private DotnetProjectionEmitter(NativeTypeDeclaration[] types, string client)
    {
        this.client = Identifier(client);
        declarations = types.ToDictionary(type => type.Id, StringComparer.Ordinal);
    }

    // This emits a new data carrier. Authored constructor and accessor bodies are not replayed.
    internal static string EmitData(
        NativeTypeDeclaration[] types,
        NativeTypeReference[] roots,
        string identity,
        string targetNamespace,
        string context,
        NativeSerializerContext? serializer = null)
    {
        if (targetNamespace.Split('.').Any(part => !SyntaxFacts.IsValidIdentifier(part)))
            throw new InvalidDataException("Data namespace must contain valid C# identifiers.");
        var emitter = new DotnetProjectionEmitter(types, context);
        foreach (var root in roots)
            emitter.Visit(root);
        var names = emitter.DataTypeNames();
        ReserveName(names, context, "generated data JSON context");
        emitter
            .output
            .AppendLine("// <auto-generated/>")
            .AppendLine("// Declaration model " + identity)
            .AppendLine("// Data carriers preserve selected declarations, not authored constructor/accessor execution.")
            .AppendLine("#nullable enable")
            .AppendLine("using System.Text.Json;")
            .AppendLine("using System.Text.Json.Serialization;")
            .AppendLine("using System.Text.Json.Serialization.Metadata;")
            .AppendLine("namespace " + targetNamespace + ";");
        foreach (var id in emitter.reachable.Order(StringComparer.Ordinal))
            emitter.EmitType(emitter.declarations[id], dataCarrier: serializer is null);
        emitter.output.AppendLine("/// <summary>JSON metadata for the selected declaration data.</summary>");
        if (serializer is null)
            emitter.output.AppendLine(
                "[global::System.Text.Json.Serialization.JsonSourceGenerationOptions(GenerationMode = global::System.Text.Json.Serialization.JsonSourceGenerationMode.Metadata, RespectNullableAnnotations = true, RespectRequiredConstructorParameters = true)]");
        else
        {
            ValidateSerializer(serializer);
            foreach (var attribute in serializer.Attributes.Where(value =>
                         value.Name == "System.Text.Json.Serialization.JsonSourceGenerationOptionsAttribute"))
                emitter.EmitAttribute(attribute);
        }

        foreach (var name in emitter
                     .reachable.Select(id => Identifier(emitter.declarations[id].Name))
                     .Concat(
                         roots.Select(root => emitter.TypeName(
                             root with
                             {
                                 Nullability = "NotAnnotated"
                             })))
                     .Distinct(StringComparer.Ordinal)
                     .Order(StringComparer.Ordinal))
            emitter.output.AppendLine(
                "[global::System.Text.Json.Serialization.JsonSerializable(typeof(" + name + "))]");
        emitter.output.AppendLine(
            "public partial class " + Identifier(context) +
            " : global::System.Text.Json.Serialization.JsonSerializerContext;");
        return emitter.output.ToString();
    }

    internal static string Emit(RemoteProjection model, string targetNamespace, string service, string client)
    {
        if (targetNamespace.Split('.').Any(part => !SyntaxFacts.IsValidIdentifier(part)))
            throw new InvalidDataException("Caller namespace must contain valid C# identifiers.");
        var emitter = new DotnetProjectionEmitter(model, client);
        return emitter.Generate(targetNamespace, service);
    }

    private string Generate(string targetNamespace, string service)
    {
        var model = this.model!;
        var selected = model.Services.SingleOrDefault(value => value.Key == service || value.SourceType == service) ??
            throw new InvalidDataException($"No unique native service '{service}'.");
        if (selected.Serializer is null)
            throw new InvalidDataException("Native caller projection requires an explicit source JSON context.");
        selected = selected with
        {
            Methods = selected.Methods.Select(WithContextArgument).ToArray()
        };
        if (selected.Methods.Length == 0)
            throw new InvalidDataException("Selected service contains no authored Remote methods.");
        if (selected.Methods.Any(method => string.IsNullOrEmpty(method.Name)))
            throw new InvalidDataException("Remote method names must be non-empty caller identifiers.");
        if (selected
                .Methods.Select(method => char.ToUpperInvariant(method.Name[0]) + method.Name[1..] + "Async")
                .Distinct(StringComparer.Ordinal)
                .Count() != selected.Methods.Length)
            throw new InvalidDataException("Remote names collide after normalization to caller Async method names.");
        foreach (var method in selected.Methods)
        {
            if (method.ReturnWrapper != (method.Stream
                    ? "System.Collections.Generic.IAsyncEnumerable<T>"
                    : method.Result.Name == "System_Void"
                        ? "System.Threading.Tasks.Task"
                        : "System.Threading.Tasks.Task<TResult>") ||
                method.Parameters.Any(parameter =>
                    parameter.RefKind != "None" || parameter.Params))
                throw new InvalidDataException(
                    $"{method.Name}: caller projection supports unary and downlink methods with ordinary wire parameters.");
            if (method.Result.Name != "System_Void")
                Visit(method.Result);
            if (method.Uplink is { } uplink)
                Visit(uplink.Type);
            foreach (var parameter in method.Parameters)
            {
                if (parameter.Optional && parameter.Default is null)
                    throw new InvalidDataException(
                        "An optional native parameter requires its authored constant default: " +
                        method.Name + "." + parameter.Name);
                if (parameter.Optional && parameter.Default is { Kind: "value" } constant &&
                    constant.Type.TrimEnd('?') is "double" or "float" or "System.Double" or "System.Single" &&
                    constant.Json is "\"NaN\"" or "\"Infinity\"" or "\"-Infinity\"" &&
                    !selected.Serializer.Attributes.Any(attribute =>
                        attribute.Name == "System.Text.Json.Serialization.JsonSourceGenerationOptionsAttribute" &&
                        attribute.NamedArguments.Any(argument => argument.Name == "NumberHandling" &&
                            int.TryParse(argument.Value.Json, out var handling) &&
                            (handling & (int)System.Text.Json.Serialization.JsonNumberHandling
                                .AllowNamedFloatingPointLiterals) != 0)))
                    throw new InvalidDataException(
                        "ProjectionUnsupported TYPM116: Non-finite optional default cannot be transmitted by the selected JSON number handling: " +
                        method.Name + "." + parameter.Name + ". Host-side omission remains supported.");
                Visit(parameter.Type);
            }
        }

        var relevantIds = reachable.Append(selected.Serializer.Id).ToHashSet(StringComparer.Ordinal);
        var blockers = model
            .Diagnostics.Where(value => value.Category == "AnalysisUnsupported" ||
                value.Symbol is null || relevantIds.Any(id => value.Symbol.StartsWith(id, StringComparison.Ordinal)) ||
                DeclarationRemoteProjection.OwnsServiceDiagnostic(model, selected, value.Symbol))
            .ToArray();
        if (blockers.Length != 0)
            throw new InvalidDataException(
                string.Join("\n", blockers.Select(value => value.Category + " " + value.Code + ": " + value.Message)));
        ValidateTypeNames(selected);
        output
            .AppendLine("// <auto-generated/>")
            .AppendLine("// Declaration model " + model.ContractIdentity)
            .AppendLine("#nullable enable")
            .AppendLine("using System.Text.Json;")
            .AppendLine("using System.Text.Json.Serialization;")
            .AppendLine("using System.Text.Json.Serialization.Metadata;")
            .AppendLine("using System.Threading;")
            .AppendLine("using System.Threading.Tasks;")
            .AppendLine("namespace " + targetNamespace + ";");
        foreach (var id in reachable.Order(StringComparer.Ordinal))
            EmitType(declarations[id]);
        foreach (var method in selected.Methods)
            EmitEnvelopes(method);
        EmitContext(selected);
        EmitClient(selected);
        return output.ToString();
    }

    private void ValidateTypeNames(NativeService service)
    {
        var callerName = client.TrimStart('@');
        if (callerName is "Info" or "CreateInfo")
            throw new InvalidDataException(
                $"Caller type name '{callerName}' conflicts with the generated Remote metadata member '{callerName}'. Choose another caller name.");
        var names = DataTypeNames();
        ReserveName(names, client, "generated client");
        ReserveName(names, client + "Json", "generated data JSON context");
        ReserveName(names, client + "CarrierJson", "generated carrier JSON context");
        if (service.Methods.Any(method => method.Context is not null || method.Scope is not null))
            ReserveName(names, client + "Scope", "generated scoped client view");
        foreach (var method in service.Methods)
        {
            var prefix = EnvelopePrefix(method);
            ReserveName(names, prefix + "Args", "generated arguments for Remote " + method.Name);
        }
    }

    private Dictionary<string, string> DataTypeNames()
    {
        var names = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var id in reachable.Order(StringComparer.Ordinal))
            ReserveName(names, declarations[id].Name, "data type " + id);
        return names;
    }

    private static void ReserveName(Dictionary<string, string> names, string name, string origin)
    {
        var identifier = Identifier(name).TrimStart('@');
        if (names.TryGetValue(identifier, out var previous))
            throw new InvalidDataException($"Caller type names collide at '{identifier}': {previous} and {origin}.");
        names.Add(identifier, origin);
    }

    private string EnvelopePrefix(NativeMethod method) => client + Identifier(method.Name).TrimStart('@');

    private static NativeMethod WithContextArgument(NativeMethod method)
    {
        if (method.Context is null || method.ContextWireType is null)
            return method;
        var name = "__cordisContext";
        while (method.Parameters.Any(parameter => parameter.Name == name))
            name += "_";
        return method with
        {
            Parameters =
            [
                new(name, method.ContextWire, method.ContextWireType, null, null, "None", false, null, false, [], ""),
                .. method.Parameters
            ]
        };
    }

    private void Visit(NativeTypeReference type)
    {
        if (type.Kind is "unsupported" or "object" || type.Rank > 1)
            throw new InvalidDataException(
                "Caller projection cannot represent type " + type.Name + " (" + type.Kind + ").");
        if (type.Nullability == "None" && !IsEnum(type) &&
            (type.Kind is "named" or "array" or "collection" || type.Name == "System_String"))
            throw new InvalidDataException(
                "Oblivious reference annotations are retained in the model but require an explicit nullable caller projection: " +
                type.Name);
        foreach (var argument in type.Arguments)
            Visit(argument);
        if (type.Kind != "named" || !reachable.Add(type.Name))
            return;
        if (!declarations.TryGetValue(type.Name, out var declaration))
            throw new InvalidDataException("Native model omits reachable declaration " + type.Name);
        if (declaration.Enumeration is not null)
            return;
        if (declaration.Kind is not ("record" or "class") || declaration.BaseType is not null ||
            declaration.TypeArguments.Length != 0)
            throw new InvalidDataException(
                "Caller projection currently supports only non-generic ordinary data records/classes without data inheritance: " +
                type.Name);
        foreach (var member in declaration.Members)
        {
            if (member.WriteAccess == "none")
                throw new InvalidDataException(
                    "ProjectionUnsupported TYPM112: read-only wire member cannot be copied into a writable caller DTO: " +
                    declaration.Id + "." + member.Name);
            Visit(member.Type);
        }

        foreach (var constructor in declaration.Constructors)
            foreach (var parameter in constructor.Parameters)
                Visit(parameter.Type);
    }

    private void EmitType(NativeTypeDeclaration type, bool dataCarrier = false)
    {
        var name = Identifier(type.Name);
        Docs(type.Documentation, filter: "type");
        foreach (var attribute in type.Attributes)
            EmitAttribute(attribute);
        if (type.Enumeration is { } enumeration)
        {
            output.AppendLine("public enum " + name + " : " + TypeName(enumeration.UnderlyingType)).AppendLine("{");
            foreach (var member in enumeration.Members)
            {
                Docs(member.Documentation, "    ");
                output.AppendLine("    " + Identifier(member.Name) + " = " + member.Value + ",");
            }

            output.AppendLine("}");
            return;
        }

        output.AppendLine("public sealed " + type.Kind + " " + name).AppendLine("{");
        var constructor = dataCarrier ? DataConstructor(type) : Constructor(type);
        if (constructor is not null)
        {
            if (dataCarrier)
                output.AppendLine("    public " + name + "() { }");
            output.AppendLine("    /// <summary>Initialize the projected data carrier.</summary>");
            Docs(type.Documentation, "    ", "constructor");
            if (constructor.JsonConstructor)
                output.AppendLine("    [JsonConstructor]");
            if (constructor.SetsRequiredMembers)
                output.AppendLine("    [global::System.Diagnostics.CodeAnalysis.SetsRequiredMembers]");
            output
                .Append("    public ")
                .Append(name)
                .Append('(')
                .Append(
                    string.Join(
                        ", ",
                        constructor.Parameters.Select(parameter => ParameterAttributes(parameter.Attributes) +
                            TypeName(parameter.Type) + " " + Identifier(parameter.Name) +
                            (parameter.Optional
                                ? " = " + Constant(parameter.Default!) +
                                (dataCarrier && parameter.Default!.Json == "null" && !Nullable(parameter.Type)
                                    ? "!"
                                    : "")
                                : ""))))
                .AppendLine(")")
                .AppendLine("    {");
            foreach (var parameter in constructor.Parameters)
            {
                if (parameter.Member is null)
                    throw new InvalidDataException(
                        "Constructor parameter has no matching public data member: " + type.Id + "." + parameter.Name);
                output.AppendLine(
                    "        this." + Identifier(parameter.Member) + " = " + Identifier(parameter.Name) + ";");
            }

            output.AppendLine("    }");
        }

        foreach (var member in type.Members)
        {
            Docs(member.Documentation, "    ");
            if (member.Accessibility != "Public" || !member.Readable)
                throw new InvalidDataException(
                    "Standalone caller cannot project a non-public/unreadable data member: " + type.Id + "." +
                    member.Name);
            foreach (var attribute in member.Attributes.Where(value =>
                         value.Name != "System.Text.Json.Serialization.JsonPropertyNameAttribute"))
                EmitAttribute(attribute, "    ");
            if (dataCarrier && member.Required && !member.JsonRequired)
                output.AppendLine("    [global::System.Text.Json.Serialization.JsonRequired]");
            output.AppendLine(
                "    [global::System.Text.Json.Serialization.JsonPropertyName(" + Literal(member.WireName) + ")]");
            output
                .Append("    public ")
                .Append(member.Required ? "required " : "")
                .Append(TypeName(member.Type))
                .Append(' ')
                .Append(Identifier(member.Name));
            if (member.Kind != "field")
                output.Append(" { get; ").Append(member.WriteAccess).Append("; }");
            if (member.Initializer is not null)
                output.Append(" = ").Append(Constant(member.Initializer)).Append(';');
            else if (member.Kind == "field")
                output.Append(" = default!;");
            else if (!member.Required)
                output.Append(" = default!;");
            output.AppendLine();
        }

        output.AppendLine("}");
    }

    private static NativeConstructor? DataConstructor(NativeTypeDeclaration type)
    {
        // STJ's generated initializer path otherwise overwrites omitted init members with default(T).
        var bound = type
            .Members.Where(member => member.Required || member.WriteAccess == "init")
            .OrderByDescending(member => member.Required)
            .ToArray();
        if (bound.Length == 0)
            return null;
        if (type.Members.Select(member => member.Name).Distinct(StringComparer.OrdinalIgnoreCase).Count() !=
            type.Members.Length)
            throw new InvalidDataException("Data constructor member names collide ignoring case: " + type.Id);
        return new(
            "Public",
            true,
            bound.Any(member => member.Required),
            bound
                .Select(member =>
                    new NativeConstructorParameter(
                        member.Name,
                        member.Type,
                        member.Name,
                        !member.Required,
                        member.Required ? null : member.Initializer ?? new("carrierDefault", "", "null"),
                        member
                            .Attributes.Where(attribute => attribute.Name.StartsWith(
                                "System.Diagnostics.CodeAnalysis.",
                                StringComparison.Ordinal))
                            .ToArray()))
                .ToArray());
    }

    private static NativeConstructor? Constructor(NativeTypeDeclaration type)
    {
        var marked = type.Constructors.Where(value => value.JsonConstructor).ToArray();
        if (marked.Length > 1 || marked.Any(value => value.Accessibility != "Public"))
            throw new InvalidDataException("Standalone caller supports one public JSON constructor: " + type.Id);
        if (marked.Length == 1)
            return marked[0];
        var publicConstructors = type.Constructors.Where(value => value.Accessibility == "Public").ToArray();
        return publicConstructors.FirstOrDefault(value => value.Parameters.Length == 0) ??
            (publicConstructors.Length == 1
                ? publicConstructors[0]
                : throw new InvalidDataException("Ambiguous or absent public data constructor: " + type.Id));
    }

    private void EmitEnvelopes(NativeMethod method)
    {
        var prefix = EnvelopePrefix(method);
        output.AppendLine("internal sealed class " + prefix + "Args").AppendLine("{");
        foreach (var parameter in method.Parameters)
        {
            // Identity null is a present wire value; the Host codec decides whether it is valid.
            var envelopeType = parameter.Lookup is not null ||
                method.Context is not null && parameter.Wire == method.ContextWire
                    ? parameter.Type with
                    {
                        Nullability = "Annotated"
                    }
                    : parameter.Type;
            foreach (var attribute in parameter.Attributes)
                EmitAttribute(attribute, "    ");
            output.AppendLine(
                "    [JsonPropertyName(" + Literal(parameter.Wire) +
                "), JsonIgnore(Condition = JsonIgnoreCondition." +
                (OmitNullDefault(parameter) ? "WhenWritingNull" : "Never") +
                ")] public " + TypeName(envelopeType) + " " +
                Identifier(parameter.Name) + " { get; set; } = default!;");
        }

        output.AppendLine("}");
    }

    private static void ValidateSerializer(NativeSerializerContext serializer)
    {
        foreach (var attribute in serializer.Attributes.Where(value =>
                     value.Name == "System.Text.Json.Serialization.JsonSourceGenerationOptionsAttribute"))
        {
            if (attribute.NamedArguments.Any(value => value.Name == "Converters"))
                throw new InvalidDataException("Context converters require a separately supported projection.");
            var mode = attribute.NamedArguments.FirstOrDefault(value => value.Name == "GenerationMode")?.Value;
            if (mode is not null && mode.Json is not ("0" or "1"))
                throw new InvalidDataException(
                    "Caller requires metadata-capable JSON generation, not serialization-only mode.");
            if (attribute.NamedArguments.Any(value =>
                    value.Name == "PreferredObjectCreationHandling" && value.Value.Json != "0"))
                throw new InvalidDataException(
                    "Populate object creation semantics require a separately supported caller projection.");
        }

        foreach (var attribute in serializer.Attributes.Where(value =>
                     value.Name == "System.Text.Json.Serialization.JsonSerializableAttribute"))
            if (attribute.NamedArguments.Any(value =>
                    value.Name == "GenerationMode" && value.Value.Json is not ("0" or "1")))
                throw new InvalidDataException(
                    "Per-type serialization-only metadata does not support a standalone caller decoder.");
    }

    private void EmitContext(NativeService service)
    {
        ValidateSerializer(service.Serializer!);
        var options = service
            .Serializer!
            .Attributes.Where(value =>
                value.Name == "System.Text.Json.Serialization.JsonSourceGenerationOptionsAttribute")
            .ToArray();
        var roots = service
            .Methods.SelectMany(method => method
                .Parameters.Select(parameter => parameter.Type)
                .Append(method.Result)
                .Concat(method.Uplink is { } input ? [input.Type] : []))
            .Where(type => type.Name != "System_Void")
            .Select(type => type.Kind == "nullable" ? TypeName(type) : TypeName(type).TrimEnd('?'))
            .Concat(reachable.Select(id => Identifier(declarations[id].Name)))
            .Distinct(StringComparer.Ordinal)
            .Order(StringComparer.Ordinal)
            .ToArray();
        if (roots.Length > 0)
        {
            output.AppendLine("/// <summary>Static JSON metadata for the generated client's public data.</summary>");
            foreach (var attribute in options)
                EmitAttribute(attribute);
            foreach (var root in roots)
                output.AppendLine("[JsonSerializable(typeof(" + root + "))]");
            output.AppendLine("public partial class " + client + "Json : JsonSerializerContext;");
        }

        foreach (var attribute in options)
            EmitAttribute(attribute);
        foreach (var method in service.Methods)
        {
            var prefix = EnvelopePrefix(method);
            output
                .AppendLine("[JsonSerializable(typeof(" + prefix + "Args))]");
        }

        output.AppendLine("internal partial class " + client + "CarrierJson : JsonSerializerContext;");
    }

    private void EmitClient(NativeService service)
    {
        output.AppendLine(
            $$"""
              /// <summary>A generated Remote contribution borrowing a shared Connection.</summary>
              public sealed class {{client}} : global::Cordis.Composition.TypertClient, global::Cordis.Composition.ITypertNamedRemote
              {
                  /// <summary>Create a client without transferring Connection ownership.</summary>
                  public {{client}}(global::Cordis.Composition.TypertConnection connection) : base(connection) { }
              """);
        EmitInfo(service);
        foreach (var method in service.Methods.Where(method => method.Context is null))
            EmitCall(service, method, scoped: false);
        if (service.Methods.Any(method => method.Context is not null || method.Scope is not null))
            EmitScopedClient(service);
        output.Append(nullabilityHelpers);
        output.AppendLine("}");
    }

    private void EmitCall(NativeService service, NativeMethod method, bool scoped)
    {
        var key = scoped ? method.Context ?? method.Scope?.Context : null;
        var wire = method.Context is not null ? method.ContextWire : method.Scope?.Wire;
        var bound = key is null ? null : method.Parameters.Single(parameter => parameter.Wire == wire);
        var parameters = method.Parameters.Where(parameter => !ReferenceEquals(parameter, bound)).ToArray();
        var local = "__cordis";
        while (parameters.Any(parameter => parameter.Name.StartsWith(local, StringComparison.Ordinal)))
            local += "_";
        var token = parameters.Any(parameter => parameter.Name == "cancellationToken")
            ? local + "CancellationToken"
            : "cancellationToken";
        var signature = string.Join(
            ", ",
            parameters.Select(parameter =>
                ParameterAttributes(parameter.Attributes) + TypeName(parameter.Type) + " " +
                Identifier(parameter.Name) +
                (parameter.Optional
                    ? " = " + Constant(parameter.Default!) + (OmitNullDefault(parameter) ? "!" : "")
                    : "")));
        if (signature.Length > 0)
            signature += ", ";
        signature += "CancellationToken " + token + " = default";
        var name = Identifier(char.ToUpperInvariant(method.Name[0]) + method.Name[1..] + "Async");
        var noValue = method.Result.Name == "System_Void";
        var result = noValue ? "" : TypeName(method.Result);
        var runtimeResult = method.Result.Kind == "nullable" ? result : result.TrimEnd('?');
        var prefix = EnvelopePrefix(method);
        var owner = scoped ? "this.owner" : "this";
        var inputType = method.Uplink is { } input ? TypeName(input.Type) : null;
        if (method.Uplink?.Optional == true)
            inputType = "global::Cordis.Composition.RemoteOptional<" + inputType + ">";
        var returnType = noValue
            ? "RemoteResult"
            : method.Stream
                ? "RemoteStreamHandle<" + result + (inputType is null ? "" : ", " + inputType) + ">"
                : "RemoteResult<" + result + ">";
        var invoke = inputType is not null ? "OpenDuplexAsync<" + prefix + "Args, " + result + ", " + inputType + ">"
            : method.Stream ? "OpenStreamAsync" : "InvokeAsync";
        Docs(method.Documentation, "    ");
        output
            .AppendLine(
                "    public Task<global::Cordis.Composition." + returnType + "> " + name + "(" + signature + ")")
            .AppendLine("    {")
            .AppendLine("        return " + owner + "." + invoke + "(")
            .AppendLine("            " + Literal(service.Namespace + "/" + method.Name) + ",");
        if (bound is null)
            output.AppendLine("            () => Task.FromResult(new " + prefix + "Args {");
        else
        {
            output
                .AppendLine("            async () => {")
                .AppendLine(
                    "                var " + local + "Identity = await " + owner + ".ReadIdentityAsync<" +
                    TypeName(bound.Type) + ">(this.callerContext, this.registry, " + Literal(key!) +
                    ").ConfigureAwait(false);")
                .AppendLine("                return new " + prefix + "Args {");
        }

        output.AppendLine(
            string.Join(
                ",\n",
                method.Parameters.Select(parameter =>
                    "                    " + Identifier(parameter.Name) + " = " + (ReferenceEquals(parameter, bound)
                        ? local + "Identity"
                        : Identifier(parameter.Name)))));
        output
            .AppendLine(bound is null ? "            })," : "                };\n            },")
            .AppendLine(
                "            (JsonTypeInfo<" + prefix + "Args>)" + client + "CarrierJson.Default.GetTypeInfo(typeof(" +
                prefix + "Args))!,");
        if (!noValue)
            output
                .AppendLine(
                    "            (JsonTypeInfo<" + result + ">)" + client + "Json.Default.GetTypeInfo(typeof(" +
                    runtimeResult + "))!,")
                .AppendLine(
                    "            " + (method.Result.Kind == "json" || Nullable(method.Result) ? "true" : "false") +
                    ",");
        if (method.Uplink is { } uplink)
        {
            var codec = Codec(uplink.Type);
            if (uplink.Optional)
                codec = "global::Cordis.Composition.TypertCodec.CreateOptional<" + TypeName(uplink.Type) + ">(" +
                    codec + ")";
            output.AppendLine("            " + codec + ",");
        }

        output
            .AppendLine("            " + token + ");")
            .AppendLine("    }");
    }

    private string Codec(NativeTypeReference type, bool disallowNull = false)
    {
        if (type.Name == "System_Void")
            return "global::Cordis.Composition.TypertCodec.Void";
        if (disallowNull)
            type = type.Kind == "nullable"
                ? type.Arguments[0]
                : type with
                {
                    Nullability = "NotAnnotated"
                };
        var name = TypeName(type);
        var runtime = type.Kind == "nullable" ? name : name.TrimEnd('?');
        var metadata = "(JsonTypeInfo<" + runtime + ">)" + client + "Json.Default.GetTypeInfo(typeof(" + runtime +
            "))!";
        var collection = type.Kind == "collection" || type.Kind == "array" && type.Arguments[0].Name != "System_Byte";
        if (collection)
        {
            var dictionary = type.Kind == "collection" && type.Arguments.Length == 2;
            return "global::Cordis.Composition.TypertCodec." + (dictionary ? "CreateDictionary" : "CreateSequence") +
                "(" + metadata + ", " + Codec(type.Arguments[dictionary ? 1 : 0]) +
                ", nullable: " + (Nullable(type) ? "true" : "false") + ")";
        }

        var query = "__CordisNullability" + nullabilityIndex++;
        nullabilityHelpers.Append(NullabilityProjection.Native(type, declarations, query));
        return "global::Cordis.Composition.TypertCodec.CreateDeclared(" + metadata + ", " + query + ")";
    }

    private void EmitScopedClient(NativeService service)
    {
        output.AppendLine(
            $$"""
                  /// <summary>Borrow a caller Context and registry; read their current adapter for every call.</summary>
                  public {{client}}Scope ForContext(global::Cordis.Context callerContext, global::Cordis.Composition.TypertRegistry registry)
                  {
                      global::System.ArgumentNullException.ThrowIfNull(callerContext);
                      global::System.ArgumentNullException.ThrowIfNull(registry);
                      return new(this, callerContext, registry);
                  }
                  private async Task<T> ReadIdentityAsync<T>(global::Cordis.Context callerContext, global::Cordis.Composition.TypertRegistry registry, string key)
                  {
                      object? value = global::Cordis.Undefined.Value;
                      await callerContext.RunAsync(_ =>
                      {
                          var adapter = registry.GetClientContext(key) ?? throw new global::System.InvalidOperationException("No Client Context adapter for " + key);
                          value = adapter.Identity(callerContext);
                          return Task.CompletedTask;
                      }).ConfigureAwait(false);
                      if (global::System.Object.ReferenceEquals(value, global::Cordis.Undefined.Value))
                          throw new global::System.InvalidOperationException("The caller does not represent Context " + key);
                      if (value is T identity) return identity;
                      if (value is null && default(T) is null) return default!;
                      throw new global::System.InvalidOperationException("Client Context identity has the wrong wire type for " + key);
                  }
                  /// <summary>A borrowed Context view belonging to its parent contribution.</summary>
                  public sealed class {{client}}Scope
                  {
                      private readonly {{client}} owner;
                      private readonly global::Cordis.Context callerContext;
                      private readonly global::Cordis.Composition.TypertRegistry registry;
                      internal {{client}}Scope({{client}} owner, global::Cordis.Context callerContext, global::Cordis.Composition.TypertRegistry registry)
                      {
                          this.owner = owner;
                          this.callerContext = callerContext;
                          this.registry = registry;
                      }
              """);
        foreach (var method in service.Methods)
            EmitCall(service, method, scoped: true);
        output.AppendLine("    }");
    }

    private string TypeName(NativeTypeReference type)
    {
        var name = type.Kind switch
        {
            "primitive" => type.Name switch
            {
                "System_Boolean" => "bool",
                "System_Byte" => "byte",
                "System_SByte" => "sbyte",
                "System_Int16" => "short",
                "System_UInt16" => "ushort",
                "System_Int32" => "int",
                "System_UInt32" => "uint",
                "System_Int64" => "long",
                "System_UInt64" => "ulong",
                "System_Single" => "float",
                "System_Double" => "double",
                "System_Decimal" => "decimal",
                "System_Char" => "char",
                "System_String" => "string",
                _ => throw new InvalidDataException("Unsupported CLR primitive " + type.Name)
            },
            "json" => "global::System.Text.Json.JsonElement",
            "guid" => "global::System.Guid",
            "named" => Identifier(declarations[type.Name].Name),
            "nullable" => TypeName(type.Arguments.Single()).TrimEnd('?') + "?",
            "array" => TypeName(type.Arguments.Single()) + "[]",
            "collection" => "global::" + type.Name[..type.Name.IndexOf('<')] + "<" +
                string.Join(", ", type.Arguments.Select(TypeName)) + ">",
            _ => throw new InvalidDataException("Unsupported native type kind " + type.Kind)
        };
        return type.Nullability == "Annotated" && type.Kind is not ("nullable" or "json") &&
            (type.Kind is "named" or "array" or "collection" || type.Name == "System_String")
                ? name + "?"
                : name;
    }

    private static bool Nullable(NativeTypeReference type) =>
        type.Kind == "nullable" || type.Nullability == "Annotated";

    private static bool OmitNullDefault(NativeParameter parameter) => parameter.Optional &&
        parameter.Default?.Json == "null" && Nullable(parameter.Type) &&
        parameter.Attributes.Any(attribute =>
            attribute.Name == "System.Diagnostics.CodeAnalysis.DisallowNullAttribute");

    private static string Identifier(string value) => SyntaxFacts.IsValidIdentifier(value) ? value :
        SyntaxFacts.GetKeywordKind(value) != SyntaxKind.None ? "@" + value :
        throw new InvalidDataException("Invalid C# identifier " + value);

    private static string Literal(string value) =>
        Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, true);

    private bool IsEnum(NativeTypeReference type) => type.Kind == "named" &&
        declarations.TryGetValue(type.Name, out var declaration) && declaration.Enumeration is not null;

    private string Constant(NativeConstant value)
    {
        if (value.Kind == "enum")
        {
            var declaration = declarations.Values.SingleOrDefault(type => type.Enumeration is not null &&
                (string.IsNullOrEmpty(type.Namespace) ? type.Name : type.Namespace + "." + type.Name) == value.Type);
            if (declaration is not null)
                return "(" + Identifier(declaration.Name) + ")(" + value.Json + ")";
        }

        return DeclarationConstantEmitter.Emit(value);
    }

    private void EmitAttribute(NativeAttribute attribute, string indent = "")
        => output.AppendLine(indent + AttributeText(attribute));

    private string ParameterAttributes(NativeAttribute[] attributes) =>
        string.Concat(attributes.Select(attribute => AttributeText(attribute) + " "));

    private string AttributeText(NativeAttribute attribute)
    {
        var supported = attribute.Name is "System.FlagsAttribute"
            or "System.Text.Json.Serialization.JsonPropertyNameAttribute" or
            "System.Text.Json.Serialization.JsonIgnoreAttribute"
            or "System.Text.Json.Serialization.JsonRequiredAttribute" or
            "System.Text.Json.Serialization.JsonPropertyOrderAttribute"
            or "System.Text.Json.Serialization.JsonNumberHandlingAttribute" or
            "System.Text.Json.Serialization.JsonIncludeAttribute"
            or "System.Text.Json.Serialization.JsonSourceGenerationOptionsAttribute" or
            "System.Text.Json.Serialization.JsonUnmappedMemberHandlingAttribute" or
            "System.Diagnostics.CodeAnalysis.AllowNullAttribute"
            or "System.Diagnostics.CodeAnalysis.DisallowNullAttribute" or
            "System.Diagnostics.CodeAnalysis.MaybeNullAttribute" or "System.Diagnostics.CodeAnalysis.NotNullAttribute";
        if (!supported)
            throw new InvalidDataException(
                "JSON attribute requires an explicitly supported projection: " + attribute.Name);
        return "[global::" + attribute.Name + "(" + string.Join(
            ", ",
            attribute
                .Arguments.Select(Constant)
                .Concat(attribute.NamedArguments.Select(value => value.Name + " = " + Constant(value.Value)))) + ")]";
    }

    private void Docs(string xml, string indent = "", string? filter = null)
    {
        if (string.IsNullOrWhiteSpace(xml))
            return;
        var member = XElement.Parse(xml);
        foreach (var element in member.Elements())
        {
            if (filter == "type" && element.Name.LocalName == "param" ||
                filter == "constructor" && element.Name.LocalName != "param")
                continue;
            foreach (var line in element.ToString().Split('\n'))
                output.AppendLine(indent + "/// " + line.TrimEnd('\r'));
        }
    }
