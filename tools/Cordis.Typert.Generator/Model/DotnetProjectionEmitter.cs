using System.Text;
using System.Text.Json;
using System.Xml.Linq;
using Microsoft.CodeAnalysis.CSharp;

namespace Cordis.Typert.Generator.Model;

internal sealed class DotnetProjectionEmitter
{
    private readonly RemoteProjection? model;
    private readonly string client;
    private readonly Dictionary<string, NativeTypeDeclaration> declarations;
    private readonly HashSet<string> reachable = new(StringComparer.Ordinal);
    private readonly StringBuilder output = new();

    private DotnetProjectionEmitter(RemoteProjection model, string client) : this(model.Types, client)
    {
        this.model = model;
    }

    private DotnetProjectionEmitter(NativeTypeDeclaration[] types, string client)
    {
        this.client = Identifier(client);
        declarations = types.ToDictionary(type => type.Id, StringComparer.Ordinal);
    }

    // This emits a new data carrier. Authored constructor and accessor bodies are not replayed.
    internal static string EmitData(
        NativeTypeDeclaration[] types,
        NativeTypeReference[] roots,
        string identity,
        string targetNamespace,
        string context)
    {
        if (targetNamespace.Split('.').Any(part => !SyntaxFacts.IsValidIdentifier(part)))
            throw new InvalidDataException("Data namespace must contain valid C# identifiers.");
        var emitter = new DotnetProjectionEmitter(types, context);
        foreach (var root in roots)
            emitter.Visit(root);
        var names = emitter.DataTypeNames();
        ReserveName(names, context, "generated data JSON context");
        emitter
            .output
            .AppendLine("// <auto-generated/>")
            .AppendLine("// Declaration model " + identity)
            .AppendLine("// Data carriers preserve selected declarations, not authored constructor/accessor execution.")
            .AppendLine("#nullable enable")
            .AppendLine("using System.Text.Json;")
            .AppendLine("using System.Text.Json.Serialization;")
            .AppendLine("namespace " + targetNamespace + ";");
        foreach (var id in emitter.reachable.Order(StringComparer.Ordinal))
            emitter.EmitType(emitter.declarations[id], dataCarrier: true);
        emitter.output.AppendLine(
            "[global::System.Text.Json.Serialization.JsonSourceGenerationOptions(GenerationMode = global::System.Text.Json.Serialization.JsonSourceGenerationMode.Metadata, RespectNullableAnnotations = true, RespectRequiredConstructorParameters = true)]");
        foreach (var id in emitter.reachable.Order(StringComparer.Ordinal))
            emitter.output.AppendLine(
                "[global::System.Text.Json.Serialization.JsonSerializable(typeof(" +
                Identifier(emitter.declarations[id].Name) + "))]");
        emitter.output.AppendLine(
            "public partial class " + Identifier(context) +
            " : global::System.Text.Json.Serialization.JsonSerializerContext;");
        return emitter.output.ToString();
    }

    internal static string Emit(RemoteProjection model, string targetNamespace, string service, string client)
    {
        if (targetNamespace.Split('.').Any(part => !SyntaxFacts.IsValidIdentifier(part)))
            throw new InvalidDataException("Caller namespace must contain valid C# identifiers.");
        var emitter = new DotnetProjectionEmitter(model, client);
        return emitter.Generate(targetNamespace, service);
    }

    private string Generate(string targetNamespace, string service)
    {
        var model = this.model!;
        var selected = model.Services.SingleOrDefault(value => value.Key == service || value.SourceType == service) ??
            throw new InvalidDataException($"No unique native service '{service}'.");
        if (selected.Serializer is null)
            throw new InvalidDataException("Native caller projection requires an explicit source JSON context.");
        if (selected.Methods.Length == 0)
            throw new InvalidDataException("Selected service contains no authored Remote methods.");
        if (selected.Methods.Any(method => string.IsNullOrEmpty(method.Name)))
            throw new InvalidDataException("Remote method names must be non-empty caller identifiers.");
        if (selected
                .Methods.Select(method => char.ToUpperInvariant(method.Name[0]) + method.Name[1..] + "Async")
                .Distinct(StringComparer.Ordinal)
                .Count() != selected.Methods.Length)
            throw new InvalidDataException("Remote names collide after normalization to caller Async method names.");
        foreach (var method in selected.Methods)
        {
            if (method.Context is not null ||
                method.Parameters.Any(parameter => parameter.Lookup is not null) ||
                method.ReturnWrapper != (method.Stream
                    ? "System.Collections.Generic.IAsyncEnumerable<T>"
                    : "System.Threading.Tasks.Task<TResult>") ||
                method.Parameters.Any(parameter =>
                    parameter.RefKind != "None" || parameter.Params))
                throw new InvalidDataException(
                    $"{method.Name}: caller projection supports only direct unary and downlink methods.");
            Visit(method.Result);
            foreach (var parameter in method.Parameters)
            {
                if (parameter.Optional && parameter.Default is null)
                    throw new InvalidDataException(
                        "An optional native parameter requires its authored constant default: " +
                        method.Name + "." + parameter.Name);
                Visit(parameter.Type);
            }
        }

        var relevantIds = reachable.Append(selected.Serializer.Id).ToHashSet(StringComparer.Ordinal);
        var blockers = model
            .Diagnostics.Where(value => value.Category == "AnalysisUnsupported" ||
                value.Symbol is null || relevantIds.Any(id => value.Symbol.StartsWith(id, StringComparison.Ordinal)) ||
                DeclarationRemoteProjection.OwnsServiceDiagnostic(model, selected, value.Symbol))
            .ToArray();
        if (blockers.Length != 0)
            throw new InvalidDataException(
                string.Join("\n", blockers.Select(value => value.Category + " " + value.Code + ": " + value.Message)));
        ValidateTypeNames(selected);
        output
            .AppendLine("// <auto-generated/>")
            .AppendLine("// Declaration model " + model.ContractIdentity)
            .AppendLine("#nullable enable")
            .AppendLine("using System.Net.Http;")
            .AppendLine("using System.Text.Json;")
            .AppendLine("using System.Text.Json.Serialization;")
            .AppendLine("using System.Text.Json.Serialization.Metadata;")
            .AppendLine("using System.Threading;")
            .AppendLine("using System.Threading.Tasks;")
            .AppendLine("namespace " + targetNamespace + ";");
        foreach (var id in reachable.Order(StringComparer.Ordinal))
            EmitType(declarations[id]);
        foreach (var method in selected.Methods)
            EmitEnvelopes(method);
        output.AppendLine(
            $$"""
              internal sealed class {{client}}Failure
              {
                  [JsonPropertyName("code")] public string Code { get; set; } = "";
                  [JsonPropertyName("message")] public string Message { get; set; } = "";
                  [JsonPropertyName("details")] public JsonElement? Details { get; set; }
              }
              """);
        EmitContext(selected);
        EmitClient(selected);
        return output.ToString();
    }

    private void ValidateTypeNames(NativeService service)
    {
        var names = DataTypeNames();
        ReserveName(names, client, "generated client");
        ReserveName(names, client + "Json", "generated data JSON context");
        ReserveName(names, client + "CarrierJson", "generated carrier JSON context");
        ReserveName(names, client + "Failure", "generated failure envelope");
        foreach (var method in service.Methods)
        {
            var prefix = EnvelopePrefix(method);
            ReserveName(names, prefix + "Args", "generated arguments for Remote " + method.Name);
            ReserveName(names, prefix + "Request", "generated request for Remote " + method.Name);
            ReserveName(names, prefix + "Response", "generated response for Remote " + method.Name);
        }
    }

    private Dictionary<string, string> DataTypeNames()
    {
        var names = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var id in reachable.Order(StringComparer.Ordinal))
            ReserveName(names, declarations[id].Name, "data type " + id);
        return names;
    }

    private static void ReserveName(Dictionary<string, string> names, string name, string origin)
    {
        var identifier = Identifier(name).TrimStart('@');
        if (names.TryGetValue(identifier, out var previous))
            throw new InvalidDataException($"Caller type names collide at '{identifier}': {previous} and {origin}.");
        names.Add(identifier, origin);
    }

    private string EnvelopePrefix(NativeMethod method) => client + Identifier(method.Name).TrimStart('@');

    private void Visit(NativeTypeReference type)
    {
        if (type.Kind is "unsupported" or "object" || type.Rank > 1)
            throw new InvalidDataException(
                "Caller projection cannot represent type " + type.Name + " (" + type.Kind + ").");
        if (type.Nullability == "None" &&
            (type.Kind is "named" or "array" or "collection" || type.Name == "System_String"))
            throw new InvalidDataException(
                "Oblivious reference annotations are retained in the model but require an explicit nullable caller projection: " +
                type.Name);
        foreach (var argument in type.Arguments)
            Visit(argument);
        if (type.Kind != "named" || !reachable.Add(type.Name))
            return;
        if (!declarations.TryGetValue(type.Name, out var declaration))
            throw new InvalidDataException("Native model omits reachable declaration " + type.Name);
        if (declaration.Kind is not ("record" or "class") || declaration.BaseType is not null ||
            declaration.TypeArguments.Length != 0)
            throw new InvalidDataException(
                "Caller projection currently supports only non-generic ordinary data records/classes without data inheritance: " +
                type.Name);
        foreach (var member in declaration.Members)
        {
            if (member.WriteAccess == "none")
                throw new InvalidDataException(
                    "ProjectionUnsupported TYPM112: read-only wire member cannot be copied into a writable caller DTO: " +
                    declaration.Id + "." + member.Name);
            Visit(member.Type);
        }

        foreach (var constructor in declaration.Constructors)
            foreach (var parameter in constructor.Parameters)
                Visit(parameter.Type);
    }

    private void EmitType(NativeTypeDeclaration type, bool dataCarrier = false)
    {
        var name = Identifier(type.Name);
        Docs(type.Documentation, filter: "type");
        foreach (var attribute in type.Attributes)
            EmitAttribute(attribute);
        output.AppendLine("public sealed " + type.Kind + " " + name).AppendLine("{");
        var constructor = dataCarrier ? DataConstructor(type) : Constructor(type);
        if (constructor is not null)
        {
            if (dataCarrier)
                output.AppendLine("    public " + name + "() { }");
            Docs(type.Documentation, "    ", "constructor");
            if (constructor.JsonConstructor)
                output.AppendLine("    [JsonConstructor]");
            if (constructor.SetsRequiredMembers)
                output.AppendLine("    [global::System.Diagnostics.CodeAnalysis.SetsRequiredMembers]");
            output
                .Append("    public ")
                .Append(name)
                .Append('(')
                .Append(
                    string.Join(
                        ", ",
                        constructor.Parameters.Select(parameter => ParameterAttributes(parameter.Attributes) +
                            TypeName(parameter.Type) + " " + Identifier(parameter.Name) +
                            (parameter.Optional
                                ? " = " + Constant(parameter.Default!) +
                                (dataCarrier && parameter.Default!.Json == "null" && !Nullable(parameter.Type)
                                    ? "!"
                                    : "")
                                : ""))))
                .AppendLine(")")
                .AppendLine("    {");
            foreach (var parameter in constructor.Parameters)
            {
                if (parameter.Member is null)
                    throw new InvalidDataException(
                        "Constructor parameter has no matching public data member: " + type.Id + "." + parameter.Name);
                output.AppendLine(
                    "        this." + Identifier(parameter.Member) + " = " + Identifier(parameter.Name) + ";");
            }

            output.AppendLine("    }");
        }

        foreach (var member in type.Members)
        {
            Docs(member.Documentation, "    ");
            if (member.Accessibility != "Public" || !member.Readable)
                throw new InvalidDataException(
                    "Standalone caller cannot project a non-public/unreadable data member: " + type.Id + "." +
                    member.Name);
            foreach (var attribute in member.Attributes.Where(value =>
                         value.Name != "System.Text.Json.Serialization.JsonPropertyNameAttribute"))
                EmitAttribute(attribute, "    ");
            if (dataCarrier && member.Required && !member.JsonRequired)
                output.AppendLine("    [global::System.Text.Json.Serialization.JsonRequired]");
            output.AppendLine(
                "    [global::System.Text.Json.Serialization.JsonPropertyName(" + Literal(member.WireName) + ")]");
            output
                .Append("    public ")
                .Append(member.Required ? "required " : "")
                .Append(TypeName(member.Type))
                .Append(' ')
                .Append(Identifier(member.Name));
            if (member.Kind != "field")
                output.Append(" { get; ").Append(member.WriteAccess).Append("; }");
            if (member.Initializer is not null)
                output.Append(" = ").Append(Constant(member.Initializer)).Append(';');
            else if (member.Kind == "field")
                output.Append(" = default!;");
            else if (!member.Required)
                output.Append(" = default!;");
            output.AppendLine();
        }

        output.AppendLine("}");
    }

    private static NativeConstructor? DataConstructor(NativeTypeDeclaration type)
    {
        // STJ's generated initializer path otherwise overwrites omitted init members with default(T).
        var bound = type
            .Members.Where(member => member.Required || member.WriteAccess == "init")
            .OrderByDescending(member => member.Required)
            .ToArray();
        if (bound.Length == 0)
            return null;
        if (type.Members.Select(member => member.Name).Distinct(StringComparer.OrdinalIgnoreCase).Count() !=
            type.Members.Length)
            throw new InvalidDataException("Data constructor member names collide ignoring case: " + type.Id);
        return new(
            "Public",
            true,
            bound.Any(member => member.Required),
            bound
                .Select(member =>
                    new NativeConstructorParameter(
                        member.Name,
                        member.Type,
                        member.Name,
                        !member.Required,
                        member.Required ? null : member.Initializer ?? new("carrierDefault", "", "null"),
                        member
                            .Attributes.Where(attribute => attribute.Name.StartsWith(
                                "System.Diagnostics.CodeAnalysis.",
                                StringComparison.Ordinal))
                            .ToArray()))
                .ToArray());
    }

    private static NativeConstructor? Constructor(NativeTypeDeclaration type)
    {
        var marked = type.Constructors.Where(value => value.JsonConstructor).ToArray();
        if (marked.Length > 1 || marked.Any(value => value.Accessibility != "Public"))
            throw new InvalidDataException("Standalone caller supports one public JSON constructor: " + type.Id);
        if (marked.Length == 1)
            return marked[0];
        var publicConstructors = type.Constructors.Where(value => value.Accessibility == "Public").ToArray();
        return publicConstructors.FirstOrDefault(value => value.Parameters.Length == 0) ??
            (publicConstructors.Length == 1
                ? publicConstructors[0]
                : throw new InvalidDataException("Ambiguous or absent public data constructor: " + type.Id));
    }

    private void EmitEnvelopes(NativeMethod method)
    {
        var prefix = EnvelopePrefix(method);
        output.AppendLine("internal sealed class " + prefix + "Args").AppendLine("{");
        foreach (var parameter in method.Parameters)
        {
            foreach (var attribute in parameter.Attributes)
                EmitAttribute(attribute, "    ");
            output.AppendLine(
                "    [JsonPropertyName(" + Literal(parameter.Wire) +
                "), JsonIgnore(Condition = JsonIgnoreCondition." +
                (OmitNullDefault(parameter) ? "WhenWritingNull" : "Never") +
                ")] public " + TypeName(parameter.Type) + " " +
                Identifier(parameter.Name) + " { get; set; } = default!;");
        }

        output
            .AppendLine("}")
            .AppendLine("internal sealed class " + prefix + "Request")
            .AppendLine("{")
            .AppendLine(
                "    [JsonPropertyName(\"args\"), JsonIgnore(Condition = JsonIgnoreCondition.Never)] public " + prefix +
                "Args Args { get; set; } = new();")
            .AppendLine("}")
            .AppendLine("internal sealed class " + prefix + "Response")
            .AppendLine("{")
            .AppendLine("    [JsonPropertyName(\"ok\")] public bool Ok { get; set; }")
            .AppendLine(
                "    [JsonPropertyName(\"value\")] public " + TypeName(method.Result) +
                " Value { get; set; } = default!;")
            .AppendLine("    [JsonPropertyName(\"error\")] public " + client + "Failure? Error { get; set; }")
            .AppendLine("}");
    }

    private void EmitContext(NativeService service)
    {
        foreach (var attribute in service.Serializer!.Attributes.Where(value =>
                     value.Name == "System.Text.Json.Serialization.JsonSourceGenerationOptionsAttribute"))
        {
            if (attribute.NamedArguments.Any(value => value.Name == "Converters"))
                throw new InvalidDataException("Context converters require a separately supported projection.");
            var mode = attribute.NamedArguments.FirstOrDefault(value => value.Name == "GenerationMode")?.Value;
            if (mode is not null && mode.Json is not ("0" or "1"))
                throw new InvalidDataException(
                    "Caller requires metadata-capable JSON generation, not serialization-only mode.");
            if (attribute.NamedArguments.Any(value =>
                    value.Name == "PreferredObjectCreationHandling" && value.Value.Json != "0"))
                throw new InvalidDataException(
                    "Populate object creation semantics require a separately supported caller projection.");
        }

        foreach (var attribute in service.Serializer.Attributes.Where(value =>
                     value.Name == "System.Text.Json.Serialization.JsonSerializableAttribute"))
            if (attribute.NamedArguments.Any(value =>
                    value.Name == "GenerationMode" && value.Value.Json is not ("0" or "1")))
                throw new InvalidDataException(
                    "Per-type serialization-only metadata does not support a standalone caller decoder.");
        var options = service
            .Serializer.Attributes.Where(value =>
                value.Name == "System.Text.Json.Serialization.JsonSourceGenerationOptionsAttribute")
            .ToArray();
        output.AppendLine("/// <summary>Static JSON metadata for the generated client's public data.</summary>");
        foreach (var attribute in options)
            EmitAttribute(attribute);
        var roots = service
            .Methods.SelectMany(method => method.Parameters.Select(parameter => parameter.Type).Append(method.Result))
            .Select(type => type.Kind == "nullable" ? TypeName(type) : TypeName(type).TrimEnd('?'))
            .Concat(reachable.Select(id => Identifier(declarations[id].Name)))
            .Distinct(StringComparer.Ordinal)
            .Order(StringComparer.Ordinal);
        foreach (var root in roots)
            output.AppendLine("[JsonSerializable(typeof(" + root + "))]");
        output.AppendLine("public partial class " + client + "Json : JsonSerializerContext;");
        foreach (var attribute in options)
            EmitAttribute(attribute);
        foreach (var method in service.Methods)
        {
            var prefix = EnvelopePrefix(method);
            output
                .AppendLine("[JsonSerializable(typeof(" + prefix + "Request))]")
                .AppendLine("[JsonSerializable(typeof(" + prefix + "Response))]");
        }

        output.AppendLine("internal partial class " + client + "CarrierJson : JsonSerializerContext;");
    }

    private void EmitClient(NativeService service)
    {
        output.AppendLine(
            $$"""
              /// <summary>A generated native Remote client. The caller owns the supplied HttpClient.</summary>
              public sealed class {{client}} : global::System.IDisposable
              {
                  private readonly HttpClient httpClient;
                  private readonly global::System.Uri remoteBase;
                  private readonly CancellationTokenSource lifetime = new();
                  private int disposed;
                  /// <summary>Create a Remote client using the supplied caller-owned transport.</summary>
                  public {{client}}(HttpClient borrowedClient, global::System.Uri remoteBase)
                  {
                      global::System.ArgumentNullException.ThrowIfNull(borrowedClient);
                      global::System.ArgumentNullException.ThrowIfNull(remoteBase);
                      if (!remoteBase.IsAbsoluteUri) throw new global::System.ArgumentException("Remote base must be absolute.", nameof(remoteBase));
                      httpClient = borrowedClient;
                      this.remoteBase = remoteBase;
                  }
                  private void CheckActive()
                  {
                      if (global::System.Threading.Volatile.Read(ref disposed) != 0)
                          throw new global::Cordis.Composition.RemoteError("gateway/internal", "The Remote contribution was withdrawn.");
                  }
                  /// <summary>Withdraw this client and cancel its outstanding transport requests.</summary>
                  public void Dispose()
                  {
                      if (global::System.Threading.Interlocked.Exchange(ref disposed, 1) == 0)
                          lifetime.Cancel();
                  }
              """);
        foreach (var method in service.Methods)
        {
            var apiName = Identifier(char.ToUpperInvariant(method.Name[0]) + method.Name[1..] + "Async");
            var prefix = EnvelopePrefix(method);
            var scope = "__cordis";
            while (method.Parameters.Any(parameter => parameter.Name.StartsWith(scope, StringComparison.Ordinal)))
                scope += "_";
            var token = method.Parameters.Any(parameter => parameter.Name == "cancellationToken")
                ? scope + "CancellationToken"
                : "cancellationToken";
            Docs(method.Documentation, "    ");
            if (method.Stream)
            {
                EmitStreamMethod(service, method, apiName, prefix, scope, token);
                continue;
            }

            output
                .Append("    public async Task<")
                .Append(TypeName(method.Result))
                .Append("> ")
                .Append(apiName)
                .Append('(')
                .Append(
                    string.Join(
                        ", ",
                        method.Parameters.Select(parameter =>
                            ParameterAttributes(parameter.Attributes) + TypeName(parameter.Type) + " " +
                            Identifier(parameter.Name) +
                            (parameter.Optional
                                ? " = " + Constant(parameter.Default!) + (OmitNullDefault(parameter) ? "!" : "")
                                : ""))))
                .Append(method.Parameters.Length == 0 ? "" : ", ")
                .AppendLine("CancellationToken " + token + " = default)")
                .AppendLine("    {")
                .AppendLine("        this.CheckActive();")
                .AppendLine(
                    "        using var " + scope + "Lifetime = CancellationTokenSource.CreateLinkedTokenSource(" +
                    token + ", this.lifetime.Token);")
                .AppendLine("        try")
                .AppendLine("        {")
                .AppendLine(
                    "            var " + scope + "Request = new " + prefix + "Request { Args = new " + prefix +
                    "Args {")
                .AppendLine(
                    string.Join(
                        ",\n",
                        method.Parameters.Select(parameter =>
                            "                " + Identifier(parameter.Name) + " = " + Identifier(parameter.Name))))
                .AppendLine("            } };")
                .AppendLine(
                    "            var " + scope + "RequestMetadata = (JsonTypeInfo<" + prefix + "Request>)" + client +
                    "CarrierJson.Default.GetTypeInfo(typeof(" + prefix + "Request))!;")
                .AppendLine(
                    "            using var " + scope +
                    "Content = new ByteArrayContent(JsonSerializer.SerializeToUtf8Bytes(" + scope + "Request, " +
                    scope + "RequestMetadata));")
                .AppendLine(
                    "            " + scope +
                    "Content.Headers.ContentType = new global::System.Net.Http.Headers.MediaTypeHeaderValue(\"application/json\");")
                .AppendLine(
                    "            var " + scope +
                    "Url = new global::System.Uri(this.remoteBase.AbsoluteUri.TrimEnd('/') + \"/\" + " + Literal(
                        Uri.EscapeDataString(service.Namespace) + "/" + Uri.EscapeDataString(method.Name)) + ");")
                .AppendLine(
                    "            using var " + scope + "Response = await this.httpClient.PostAsync(" + scope + "Url, " +
                    scope + "Content, " + scope + "Lifetime.Token).ConfigureAwait(false);")
                .AppendLine("            this.CheckActive();")
                .AppendLine("            " + scope + "Lifetime.Token.ThrowIfCancellationRequested();")
                .AppendLine(
                    "            if (!" + scope +
                    "Response.IsSuccessStatusCode) throw new global::Cordis.Composition.RemoteError(\"gateway/protocol\", \"HTTP \" + (int)" +
                    scope + "Response.StatusCode);")
                .AppendLine(
                    "            var " + scope + "Json = await " + scope + "Response.Content.ReadAsStringAsync(" +
                    scope + "Lifetime.Token).ConfigureAwait(false);")
                .AppendLine("            this.CheckActive();")
                .AppendLine("            " + scope + "Lifetime.Token.ThrowIfCancellationRequested();")
                .AppendLine("            using var " + scope + "Document = JsonDocument.Parse(" + scope + "Json);")
                .AppendLine(
                    "            if (!" + scope + "Document.RootElement.TryGetProperty(\"ok\", out var " + scope +
                    "Ok) || " + scope +
                    "Ok.ValueKind is not (JsonValueKind.True or JsonValueKind.False)) throw new JsonException(\"Invalid Remote result envelope.\");")
                .AppendLine(
                    "            if (" + scope + "Ok.GetBoolean() && !" + scope +
                    "Document.RootElement.TryGetProperty(\"value\", out var " + scope +
                    "Value)) throw new JsonException(\"Remote result is missing its value.\");")
                .AppendLine(
                    "            var " + scope + "Metadata = (JsonTypeInfo<" + prefix + "Response>)" + client +
                    "CarrierJson.Default.GetTypeInfo(typeof(" + prefix + "Response))!;")
                .AppendLine(
                    "            var " + scope + "Result = JsonSerializer.Deserialize(" + scope + "Json, " + scope +
                    "Metadata) ?? throw new JsonException(\"Null Remote envelope.\");")
                .AppendLine("            this.CheckActive();")
                .AppendLine("            " + scope + "Lifetime.Token.ThrowIfCancellationRequested();")
                .AppendLine("            if (!" + scope + "Result.Ok)")
                .AppendLine("            {")
                .AppendLine(
                    "                var " + scope + "Failure = " + scope +
                    "Result.Error ?? throw new JsonException(\"Remote failure is missing its error.\");")
                .AppendLine(
                    "                throw new global::Cordis.Composition.RemoteError(" + scope + "Failure.Code, " +
                    scope + "Failure.Message, " + scope + "Failure.Details);")
                .AppendLine("            }");
            if (method.Result.Kind != "json" && !Nullable(method.Result))
                output.AppendLine(
                    "            if (" + scope +
                    "Document.RootElement.GetProperty(\"value\").ValueKind == JsonValueKind.Null) throw new JsonException(\"Non-null native result cannot be null.\");");
            output
                .AppendLine("            return " + scope + "Result.Value;")
                .AppendLine("        }")
                .AppendLine("        catch (global::System.Exception " + scope + "Error)")
                .AppendLine("        {")
                .AppendLine("            this.CheckActive();")
                .AppendLine("            if (" + scope + "Error is global::Cordis.Composition.RemoteError) throw;")
                .AppendLine(
                    "            throw new global::Cordis.Composition.RemoteError(" + token +
                    ".IsCancellationRequested ? \"gateway/cancelled\" : \"gateway/internal\", " + scope +
                    "Error.Message, innerException: " + scope + "Error);")
                .AppendLine("        }")
                .AppendLine("    }");
        }

        if (service.Methods.Any(method => method.Stream))
            EmitStreamReader();
        output.AppendLine("}");
    }

    private void EmitStreamMethod(
        NativeService service,
        NativeMethod method,
        string apiName,
        string prefix,
        string scope,
        string token)
    {
        var parameters = string.Join(
            ", ",
            method.Parameters.Select(parameter =>
                ParameterAttributes(parameter.Attributes) + TypeName(parameter.Type) + " " +
                Identifier(parameter.Name) +
                (parameter.Optional
                    ? " = " + Constant(parameter.Default!) + (OmitNullDefault(parameter) ? "!" : "")
                    : "")));
        if (parameters.Length != 0)
            parameters += ", ";
        var assignments = string.Join(
            ", ",
            method.Parameters.Select(parameter =>
                Identifier(parameter.Name) + " = " + Identifier(parameter.Name)));
        var endpoint = Literal(
